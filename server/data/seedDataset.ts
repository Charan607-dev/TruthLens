function escapeCsv(val: string): string {
  if (val.includes(',') || val.includes('"') || val.includes('\n')) {
    return `"${val.replace(/"/g, '""')}"`;
  }
  return val;
}

export function ensureSeedDatasetCsv(datasetsDir: string): string {
  fs.mkdirSync(datasetsDir, { recursive: true });
  const filePath = path.join(datasetsDir, 'welfake_curated_benchmark.csv');

  const corpus: SeedRow[] = [...REAL_ARTICLES, ...FAKE_ARTICLES];
  const lines = ['title,text,subject,date,label'];
  for (const row of corpus) {
    lines.push(
      [
        escapeCsv(row.title),
        escapeCsv(row.text),
        escapeCsv(row.subject),
        escapeCsv(row.date),
        escapeCsv(row.label),
      ].join(',')
    );
  }
  fs.writeFileSync(filePath, lines.join('\n'), 'utf8');
  return filePath;
}
